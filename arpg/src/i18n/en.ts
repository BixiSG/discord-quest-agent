/** A key-safe form of an English name: "Butcher's Rhythm" -> "butcher_s_rhythm". */
export const slug = (s: string): string => s.toLowerCase().replace(/[^a-z0-9]+/g, "_").replace(/^_|_$/g, "");

const TYPE_EN: Record<string, string> = { phys: "physical", fire: "fire", cold: "cold", lightning: "lightning", chaos: "chaos" };

/** Stat names as modifier lines use them (a "%" stat reads "+8% fire resistance"). */
const STAT_EN: Record<string, string> = {
    life: "maximum life", mana: "maximum mana", energyShield: "maximum energy shield", lifeRegen: "life regenerated per second",
    lifeRegenPct: "of life regenerated per second", manaRegen: "mana regenerated per second", armour: "armour", evasion: "evasion",
    block: "chance to block", str: "Might", dex: "Grace", int: "Wit", accuracy: "accuracy", damage: "damage", critChance: "critical chance",
    critMulti: "critical multiplier", attackSpeed: "attack speed", castSpeed: "cast speed", area: "area of effect", pierce: "projectile pierce",
    leech: "of damage leeched as life", flaskHeal: "flask healing", flaskCharges: "flask charges gained", moveSpeed: "movement speed",
    itemRarity: "rarity of items found", itemQuantity: "quantity of items found", xpGain: "experience gained", manaCost: "mana cost",
    dmgTaken: "damage taken", lifeOnKill: "life gained per kill", baseCrit: "base critical chance", skillEffect: "skill effect",
};
for (const t of DAMAGE_TYPES) {
    STAT_EN[`res.${t}`] = `${TYPE_EN[t]} resistance`;
    STAT_EN[`maxRes.${t}`] = `maximum ${TYPE_EN[t]} resistance`;
    STAT_EN[`pen.${t}`] = `${TYPE_EN[t]} penetration`;
    STAT_EN[`convert.${t}`] = `of physical damage converted to ${TYPE_EN[t]}`;
    STAT_EN[`addMin.${t}`] = `minimum added ${TYPE_EN[t]} damage`;
    STAT_EN[`addMax.${t}`] = `maximum added ${TYPE_EN[t]} damage`;
}

/** Stats whose flat value is a percentage. */
export const PCT_STATS: ReadonlySet<string> = new Set(["lifeRegenPct", "block", "critMulti", "leech", "baseCrit",
    ...DAMAGE_TYPES.flatMap(t => [`res.${t}`, `maxRes.${t}`, `pen.${t}`, `convert.${t}`])]);

/** Skill and modifier tags as the UI shows them. */
const TAGS: Record<string, string> = {
    attack: "attack", spell: "spell", melee: "melee", projectile: "projectile", area: "area", strike: "strike", slam: "slam", bow: "bow",
    phys: "physical", fire: "fire", cold: "cold", lightning: "lightning", chaos: "chaos", elemental: "elemental",
};

/** Content keys from the data tables. */
function content(): Record<string, string> {
    const o: Record<string, string> = {};
    for (const c of Object.values(CLASSES)) { o[`class.${c.id}.name`] = c.name; o[`class.${c.id}.blurb`] = c.blurb; }
    for (const s of Object.values(SKILLS)) { o[`skill.${s.id}.name`] = s.name; o[`skill.${s.id}.blurb`] = s.blurb; }
    for (const s of Object.values(SUPPORTS)) { o[`support.${s.id}.name`] = s.name; o[`support.${s.id}.blurb`] = s.blurb; }
    for (const m of Object.values(MONSTERS)) o[`monster.${m.id}.name`] = m.name;
    for (const z of Object.values(ZONES)) {
        o[`zone.${z.id}.name`] = z.name;
        if (z.story) o[`zone.${z.id}.story`] = z.story;
        if (z.bossText) o[`zone.${z.id}.bossText`] = z.bossText;
    }
    for (const a of ACTS) { o[`act.${a.id}.name`] = a.name; o[`act.${a.id}.intro`] = a.intro; o[`act.${a.id}.outro`] = a.outro; }
    for (const b of Object.values(BASES)) o[`base.${b.id}.name`] = b.name;
    for (const a of Object.values(AFFIXES)) { o[`affix.${a.id}.label`] = a.label; o[`affix.${a.id}.text`] = a.text; o[`group.${a.group}`] = groupLabel(a.group); }
    for (const w of RARE_NAMES_A) o[`rare.a.${slug(w)}`] = w;
    for (const w of RARE_NAMES_B) o[`rare.b.${slug(w)}`] = w;
    for (const n of Object.values(PASSIVES)) o[`node.${slug(n.name)}`] = n.name;
    for (const [name, text] of Object.entries(KEYSTONE_TEXT)) o[`keystone.${slug(name)}`] = text;
    for (const a of Object.values(ASCENDANCIES)) {
        o[`asc.${a.id}.name`] = a.name; o[`asc.${a.id}.blurb`] = a.blurb;
        for (const n of a.nodes) o[`ascnode.${n.id}.name`] = n.name;
    }
    for (const c of Object.values(CURRENCIES)) { o[`currency.${c.id}.name`] = c.name; o[`currency.${c.id}.blurb`] = c.blurb; }
    for (const r of Object.values(RELICS)) {
        o[`relic.${r.id}.name`] = r.name; o[`relic.${r.id}.flavour`] = r.flavour;
        r.mods.forEach((m, i) => { o[`relic.${r.id}.mod${i}`] = m.text; });
    }
    for (const c of Object.values(COMPANIONS)) {
        o[`companion.${c.id}.name`] = c.name; o[`companion.${c.id}.blurb`] = c.blurb; o[`companion.${c.id}.where`] = c.where; o[`companion.${c.id}.bonus`] = c.bonus.text;
    }
    for (const b of BLESSINGS) { o[`blessing.${b.id}.name`] = b.name; o[`blessing.${b.id}.text`] = b.text; }
    for (const a of Object.values(MAP_AREAS)) o[`mapArea.${a.id}.name`] = a.name;
    for (const m of Object.values(MAP_MODS)) o[`mapMod.${m.id}.text`] = m.text;
    for (const n of Object.values(ATLAS)) { o[`atlas.${n.id}.name`] = n.name; o[`atlas.${n.id}.text`] = n.text; }
    for (const p of Object.values(PINNACLES)) { o[`pinnacle.${p.id}.name`] = p.name; o[`pinnacle.${p.id}.text`] = p.text; o[`pinnacle.${p.id}.sigil`] = p.sigilName; }
    for (const p of FILTER_PRESETS) { o[`preset.${p.id}.name`] = p.name; o[`preset.${p.id}.blurb`] = p.blurb; }
    for (const [k, v] of Object.entries(STAT_EN)) o[`stat.${k}`] = v;
    for (const [k, v] of Object.entries(TAGS)) o[`tag.${k}`] = v;
    return o;
}

